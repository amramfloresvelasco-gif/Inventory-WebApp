const fs=require('fs'),vm=require('vm'),assert=require('assert');
const context=vm.createContext({});
vm.runInContext(fs.readFileSync('src/ProductIndexPreview.gs','utf8'),context);
const preview=context.invPreviewProductIndex_;
const raw=[{RawMaterialId:'91',MaterialName:'Bottle',ClassOfMaterial:'Packaging',UnitOfMeasure:'Each'},
{RawMaterialId:'91',MaterialName:'Bottle',ClassOfMaterial:'Packaging',UnitOfMeasure:'Each'},
{RawMaterialId:'92',MaterialName:'Excluded',ClassOfMaterial:'Fermentation Support'}];
const fg=[{'Master Id':'73','Master Name':'Gin 750mL/12pk'}];
const packs=[{WSItemID:'73',UnitsPerCase:12,PlannerStatus:'Inactive'}];
let r=preview(raw,fg,packs);
assert.strictEqual(r.ready,true);
assert.strictEqual(r.products.length,2);
assert.strictEqual(r.products[0].Barcode,'91');
assert.strictEqual(r.products[1].Barcode,'Gin 750mL/12pk');
assert.strictEqual(r.products[1].UnitsPerCase,12);
assert.strictEqual(r.products[1].Active,true);
r=preview(raw,fg,[]);
assert.strictEqual(r.ready,false);
assert.strictEqual(r.products[1].Active,true);
assert.strictEqual(r.products[1].UnitsPerCase,'');
r=preview([...raw,{...raw[0],MaterialName:'Other'}],fg,packs);
assert.strictEqual(r.ready,false);
assert(r.issues.some(x=>x.reason.includes('Conflicting records')));
const resolve=context.invResolveSpiritsCasePacks_;
const subtype=[{BrandReleaseTypeID:'new',BrandID:'brand',ReleaseTypeName:'12pk',UnitsPerCase:12},{BrandReleaseTypeID:'old',BrandID:'brand',ReleaseTypeName:'6pk',UnitsPerCase:6}];
const product={ProductID:'p1',BrandID:'brand',ProductName:'Example',WSFinishedGoodsID:'101',SubtypeID:'new',UnitsPerCase:12};
const release={ProductID:'p1',ReleaseType:'12pk'};
let check=resolve([product],[release],subtype);
assert.strictEqual(check.ready,true);
assert.strictEqual(check.rows.length,1);
check=resolve([{...product,SubtypeID:'old'}],[release],subtype);
assert.strictEqual(check.ready,false);
assert(check.issues.some(x=>x.reason.includes('conflicts')));
check=resolve([product,{...product,ProductID:'p2'}],[release],subtype);
assert(check.issues.some(x=>x.reason.includes('Duplicate WS')));
check=resolve([product],[{...release,ReleaseType:'unknown'}],subtype);
assert(check.issues.some(x=>x.reason.includes('cannot be resolved')));
check=resolve([{...product,SubtypeID:''}],[release],subtype);
assert.strictEqual(check.ready,true);
assert.strictEqual(check.rows[0].SubtypeID,'new');
r=preview(raw,[{'Master Id':'91','Master Name':'Different FG'}],[{WSItemID:'91',UnitsPerCase:12}]);
assert.strictEqual(r.ready,true);
assert.strictEqual(r.products.length,2);
r=preview(raw,[{'Master Id':'73','Master Name':'91'}],packs);
assert.strictEqual(r.ready,false);
assert(r.issues.some(x=>x.reason.includes('Scan payload shared')));
check=resolve([product],[{...release,ReleaseType:' 12pk '}],subtype);
assert.strictEqual(check.ready,true);
console.log('ProductIndex preview and integrity guards: 22 assertions PASS');
